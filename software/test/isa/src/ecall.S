.section .text
.globl _start

# -----------------------------------------------------------------------------
# 主程序
# -----------------------------------------------------------------------------
_start:
    # 1. 初始化栈指针 (防止异常处理程序中压栈出错)
    lui sp, 0x80000     # 假设 0x80000000 是可用内存顶部 (根据你的仿真环境调整)

    # 2. 设置 mtvec (异常向量基址寄存器)
    # 我们将异常处理程序的地址写入 mtvec
    la t0, trap_handler
    csrw mtvec, t0

    # 3. 准备参数，用于验证异常发生时寄存器是否被正确保存
    li x1, 0x12345678   # 魔数 1
    li x2, 0xabcdef00   # 魔数 2
    li a0, 0            # a0 将用作返回值，初始为 0

    # 4. 触发异常
    # 执行 ecall 后，CPU 应该跳转到 trap_handler
    ecall

    # --- mret 之后从这里继续执行 ---

    # 5. 验证返回值
    # 我们期望 trap_handler 将 a0 修改为 0xDEADBEEF
    li t0, 0xDEADBEEF
    bne a0, t0, fail

    # 6. 如果一切正常，通过测试
    j pass

# -----------------------------------------------------------------------------
# 异常处理程序 (Trap Handler)
# 对应 mtvec 指向的地址
# -----------------------------------------------------------------------------
trap_handler:
    # 1. 验证异常原因 (mcause)
    # 读取 mcause，检查是否为 Machine ECALL (值为 11)
    csrr t0, mcause
    li t1, 11
    bne t0, t1, fail

    # 2. 验证寄存器保存情况 (可选)
    # 检查 x1 是否还是 0x12345678，确保上下文没乱
    li t2, 0x12345678
    bne x1, t2, fail

    # 3. 模拟系统调用功能
    # 将 a0 设置为一个特定的返回值
    li a0, 0xDEADBEEF

    # 4. 关键步骤：修改 mepc
    # 如果不修改 mepc，mret 后会再次执行 ecall，导致死循环
    # 我们需要让 mepc 指向 ecall 的下一条指令
    csrr t0, mepc       # 读取当前的 mepc (ecall 的地址)
    addi t0, t0, 4      # +4 字节 (指向下一条指令)
    csrw mepc, t0       # 写回 mepc

    # 5. 返回
    mret

# -----------------------------------------------------------------------------
# 结果输出与死循环
# -----------------------------------------------------------------------------
#----------------------------------------
.equ TOHOST_BASE, 0x0000000080001000
pass:
    li  t0, TOHOST_BASE
    li   t1, 1
    sw   t1, 0(t0)
    j    end

fail:
    li  t0, TOHOST_BASE
    li   t1, 2
    sw   t1, 0(t0)
    j    end

end:
    ebreak
#----------------------------------------
