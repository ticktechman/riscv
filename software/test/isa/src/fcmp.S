.section .text
.globl _start

_start:
    # ----------------------------------------------------
    # 步骤 1：系统初始化，开启 FPU
    # ----------------------------------------------------
    li   t0, 0x00003000       # mstatus.FS 掩码 (Bits [14:13])
    csrs mstatus, t0          # 将 FS 设为 2'b11 (Dirty/开启)，允许加载浮点数
    fscsr x0                  # 清除浮点状态寄存器 fcsr

    # ----------------------------------------------------
    # 步骤 2：使用 fld 指令，通过 PC 相对地址（或当前段内地址）加载尾部数据
    # ----------------------------------------------------
    la   t1, fp_pos_2_5       # 借助 la 获取当前代码段尾部数据的地址
    fld  fa0, 0(t1)           # 加载 +2.5

    la   t1, fp_neg_2_5       # 获取 -2.5 的地址
    fld  fa1, 0(t1)           # 加载 -2.5

    la   t1, fp_snan          # 获取 SNaN 的地址
    fld  fa2, 0(t1)           # 加载 SNaN

    # ----------------------------------------------------
    # 步骤 3：测试 FLE.D 指令 (+2.5 <= -2.5 应为 False(0))
    # ----------------------------------------------------
    fle.d a0, fa0, fa1        # a0 = (fa0 <= fa1) -> 2.5 <= -2.5
    bne  a0, x0, fail         # 如果结果不为 0 (False)，测试失败

    # ----------------------------------------------------
    # 步骤 4：测试 FLT.D 指令 (-2.5 < +2.5 应为 True(1))
    # ----------------------------------------------------
    flt.d a1, fa1, fa0        # a1 = (fa1 < fa0)  -> -2.5 < 2.5
    li   t4, 1
    bne  a1, t4, fail         # 如果结果不为 1 (True)，测试失败

    # ----------------------------------------------------
    # 步骤 5：测试 FEQ.D 遇到 SNaN 触发 NV 异常标志
    # ----------------------------------------------------
    feq.d a2, fa0, fa2        # a2 = (2.5 == SNaN)
    bne  a2, x0, fail         # 如果结果不为 0 (False)，测试失败

    # 检查 fcsr 中的 NV 标志位 (Bit 4)
    frcsr t5                  # 将当前 fcsr 的值读入 t5
    andi  t5, t5, 0x10        # 提取 NV 位 (0x10 对应 Bit 4)
    li    t6, 0x10
    bne   t5, t6, fail        # 如果 NV 位没有被硬件自动置 1，测试失败

    # ----------------------------------------------------
    # 步骤 6：收尾工作，恢复 FS状态 并通往成功
    # ----------------------------------------------------
    csrc mstatus, t0          # 清除 FS 两位
    li   t0, 0x00001000       # 构造 Initial (2'b01) 状态
    csrs mstatus, t0          # 将 FS 修正为 Initial 状态
    j    pass

#---------------------------------------------------------
# 统一测试桩（结果写回与退出机制）
#---------------------------------------------------------
.equ TOHOST_BASE, 0x0000000080001000
pass:
    li   t0, TOHOST_BASE
    li   t1, 1
    sd   t1, 0(t0)            # 写入 1 代表测试成功
    j    end

fail:
    li   t0, TOHOST_BASE
    li   t1, 2
    sd   t1, 0(t0)            # 写入 2 代表测试失败
    j    end

end:
    ebreak                    # 绝对执行墙：CPU 执行流在此彻底终结，无法越过此行

#---------------------------------------------------------
# 嵌入在代码尾部的浮点数据区（与前面的逻辑处于同一个 .text 段中）
#---------------------------------------------------------
.align 3                      # 强制 8 字节对齐，防止 fld 产生非对齐访存异常
fp_pos_2_5:  .quad 0x4004000000000000  # +2.5 的 64位十六进制编码
fp_neg_2_5:  .quad 0xC004000000000000  # -2.5 的 64位十六进制编码
fp_snan:     .quad 0x7FF0000000000001  # SNaN 的 64位十六进制编码

