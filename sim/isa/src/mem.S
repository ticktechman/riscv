.section .text
.globl _start

.equ DATA_BASE, 0x0000000080002000
_start:
    # ==========================================
    # 1. 初始化参数
    # ==========================================
    li   t0, DATA_BASE           # t0 = 地址指针 (Ptr)，指向 0x0
    li   t1, DATA_BASE           # t1 = 写入的数据 (Data)，从 0 开始
    li   t2, 10         # t2 = 循环计数器 (Count)，总共 10 字节

    # ==========================================
    # 2. 写循环 (Write Loop)
    # ==========================================
write_loop:
    sd   t1, 0(t0)       # Store Byte: 将 t1 写入到 t0 指向的内存地址

    addi t0, t0, 8       # 地址 + 1
    addi t1, t1, 8       # 数据 + 1
    addi t2, t2, -1      # 计数 - 1
    bnez t2, write_loop  # 如果计数不为0，继续写

    # ==========================================
    # 3. 重置参数准备校验
    # ==========================================
    li   t0, DATA_BASE           # 重置地址指针 Ptr = 0
    li   t1, DATA_BASE           # 重置期望数据 Data = 0
    li   t2, 10         # 重置计数器

    # ==========================================
    # 4. 读校验循环 (Read & Check Loop)
    # ==========================================
read_loop:
    ld   t3, 0(t0)       # Load Byte: 从内存读取数据到 t3

    # --- 核心校验逻辑 ---
    bne  t3, t1, fail    # [关键] 如果 读取值(t3) != 期望值(t1)，跳转 fail

    addi t0, t0, 8       # 地址 + 1
    addi t1, t1, 8       # 期望数据 + 1
    addi t2, t2, -1      # 计数 - 1
    bnez t2, read_loop   # 如果未读完，继续校验

#----------------------------------------
.equ TOHOST_BASE, 0x0000000080001000
pass:
    li  t0, TOHOST_BASE
    li   t1, 1
    sw   t1, 0(t0)
    j    end

fail:
    li  t0, TOHOST_BASE
    li   t1, 2
    sw   t1, 0(t0)
    j    end

end:
    ebreak
#----------------------------------------

