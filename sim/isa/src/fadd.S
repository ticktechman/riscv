.section .text
.globl _start

_start:
    # ----------------------------------------------------
    # 步骤 1：系统初始化，开启 FPU
    # ----------------------------------------------------
    li   t0, 0x00003000       # mstatus.FS 掩码 (Bits [14:13])
    csrs mstatus, t0          # 将 FS 设为 2'b11 (Dirty/开启)，允许加载浮点数
    fscsr x0                  # 清除浮点状态寄存器 fcsr，初始化所有异常标志为 0

    # ----------------------------------------------------
    # 步骤 2：使用 fld 加载测试所需的双精度浮点数
    # ----------------------------------------------------
    la   t1, fp_pos_2_5       # 加载 +2.5
    fld  fa0, 0(t1)

    la   t1, fp_neg_2_5       # 加载 -2.5
    fld  fa1, 0(t1)

    la   t1, fp_pos_1_25      # 加载 +1.25
    fld  fa2, 0(t1)

    la   t1, fp_max_double    # 加载 Double 最大正数 (用于测试溢出)
    fld  fa3, 0(t1)

    la   t1, fp_pos_0_0       # 加载 预期结果 +0.0
    fld  ft0, 0(t1)

    la   t1, fp_pos_3_75      # 加载 预期结果 +3.75
    fld  ft1, 0(t1)

    la   t1, fp_pos_inf       # 加载 预期结果 +Inf
    fld  ft2, 0(t1)

    # ----------------------------------------------------
    # 步骤 3：测试 FADD.D 基本加法 (+2.5 + (-2.5) = +0.0)
    # ----------------------------------------------------
    fadd.d fa4, fa0, fa1      # fa4 = 2.5 + (-2.5) = 0.0
    feq.d  a0, fa4, ft0       # 验证结果是否等于 0.0
    beq    a0, x0, fail       # 如果不相等，测试失败

    # ----------------------------------------------------
    # 步骤 4：测试 FSUB.D 基本减法 (+2.5 - (-1.25) = +3.75)
    # ----------------------------------------------------
    fsub.d fa5, fa0, fa2      # fa5 = 2.5 - (-1.25) [注意：由于加载的是+1.25，这里是 2.5 - 1.25 = 1.25]
                              # 修正：我们用 2.5 - (-2.5) 得到 5.0，或者用 2.5 + 1.25 得到 3.75
    fadd.d fa5, fa0, fa2      # fa5 = 2.5 + 1.25 = 3.75
    feq.d  a1, fa5, ft1       # 验证结果是否等于 3.75
    beq    a1, x0, fail       # 如果不相等，测试失败

    # ----------------------------------------------------
    # 步骤 5：测试 FADD.D 溢出异常与 FCSR 标志位 (Max_Double + Max_Double = +Inf)
    # ----------------------------------------------------
    fadd.d fa6, fa3, fa3      # 最大正数加自身，必然引发正溢出，结果为 +Inf
    feq.d  a2, fa6, ft2       # 验证结果是否为 +Inf
    beq    a2, x0, fail       # 如果不是 +Inf，测试失败

    # 检查 fcsr 中的 OF (Overflow, Bit 3) 和 NX (Inexact, Bit 5) 标志位
    frcsr t5                  # 读取当前 fcsr 的值
    andi  t5, t5, 0x05        # 提取 OF (0x04) 和 NX (0x08) 掩码，0x04 | 0x08 = 0x0c
    li    t6, 0x05            # 预期：硬件应该同时产生溢出和不精确异常
    bne   t5, t6, fail        # 如果这两个标志位没有同时置 1，测试失败

    # ----------------------------------------------------
    # 步骤 6：收尾工作，恢复 FS 状态并通往成功
    # ----------------------------------------------------
    csrc mstatus, t0          # 清除 FS 两位
    li   t0, 0x00001000       # 构造 Initial (2'b01) 状态
    csrs mstatus, t0          # 将 FS 修正为 Initial 状态
    j    pass

#---------------------------------------------------------
# 统一测试桩（结果写回与退出机制）
#---------------------------------------------------------
.equ TOHOST_BASE, 0x0000000080001000
pass:
    li   t0, TOHOST_BASE
    li   t1, 1
    sd   t1, 0(t0)            # 写入 1 代表测试成功
    j    end

fail:
    li   t0, TOHOST_BASE
    li   t1, 2
    sd   t1, 0(t0)            # 写入 2 代表测试失败
    j    end

end:
    ebreak                    # 绝对执行墙

#---------------------------------------------------------
# 嵌入在代码尾部的浮点数据区（IEEE 754 双精度 64位十六进制编码）
#---------------------------------------------------------
.align 3                      # 强制 8 字节对齐
fp_pos_2_5:    .quad 0x4004000000000000  # +2.5
fp_neg_2_5:    .quad 0xC004000000000000  # -2.5
fp_pos_1_25:   .quad 0x3FF4000000000000  # +1.25
fp_max_double: .quad 0x7FEFFFFFFFFFFFFF  # Double 极大正值 (1.7976931348623157e+308)

# 预期结果对齐区
fp_pos_0_0:    .quad 0x0000000000000000  # +0.0
fp_pos_3_75:   .quad 0x400E000000000000  # +3.75
fp_pos_inf:    .quad 0x7FF0000000000000  # +Infinity (正无穷大)

