.section .text
.globl _start

_start:
    # ==========================================
    # 1. 初始化参数
    # ==========================================
    li   t0, 0           # t0 = 地址指针 (Ptr)，指向 0x0
    li   t1, 0           # t1 = 写入的数据 (Data)，从 0 开始
    li   t2, 10         # t2 = 循环计数器 (Count)，总共 10 字节

    # ==========================================
    # 2. 写循环 (Write Loop)
    # ==========================================
write_loop:
    sb   t1, 0(t0)       # Store Byte: 将 t1 写入到 t0 指向的内存地址

    addi t0, t0, 1       # 地址 + 1
    addi t1, t1, 1       # 数据 + 1
    addi t2, t2, -1      # 计数 - 1
    bnez t2, write_loop  # 如果计数不为0，继续写

    # ==========================================
    # 3. 重置参数准备校验
    # ==========================================
    li   t0, 0           # 重置地址指针 Ptr = 0
    li   t1, 0           # 重置期望数据 Data = 0
    li   t2, 10         # 重置计数器

    # ==========================================
    # 4. 读校验循环 (Read & Check Loop)
    # ==========================================
read_loop:
    lb   t3, 0(t0)       # Load Byte: 从内存读取数据到 t3

    # --- 核心校验逻辑 ---
    bne  t3, t1, fail    # [关键] 如果 读取值(t3) != 期望值(t1)，跳转 fail

    addi t0, t0, 1       # 地址 + 1
    addi t1, t1, 1       # 期望数据 + 1
    addi t2, t2, -1      # 计数 - 1
    bnez t2, read_loop   # 如果未读完，继续校验

    # ==========================================
    # 5. 测试通过 (Pass)
    # ==========================================
pass:
    lui  t0, 0x2         # t0 = 0x20000 (MMIO/打印地址)
    li   t1, 'P'         # 字符 'P'
    sb   t1, 0(t0)       # 输出 P
    li   t1, '\n'         # 字符 'P'
    sb   t1, 0(t0)       # 输出 P
    j    end             # 结束

    # ==========================================
    # 6. 测试失败 (Fail)
    # ==========================================
fail:
    lui  t0, 0x2         # t0 = 0x20000
    li   t1, 'F'         # 字符 'F'
    sb   t1, 0(t0)       # 输出 F
    li   t1, '\n'         # 字符 'F'
    sb   t1, 0(t0)       # 输出 F

    # 调试技巧：把出错的地址存到低地址，方便排查
    # li t2, 0x0
    # sw t0, 0(t2)       # (可选) 保存出错时的地址

    j    end             # 死循环或停止

end:
    ebreak               # 断点，通知模拟器/CPU 停止
