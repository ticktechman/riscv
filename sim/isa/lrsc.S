.section .text
.globl _start

_start:
    # ==========================================
    # 测试 1: 基础 LR/SC 成功场景
    # ==========================================
    li   x10, 0x0000000080002000     # 数据基址 (64位完整地址)
    li   x11, 100
    sw   x11, 0(x10)         # 初始化内存为 100

    lr.w x12, 0(x10)         # 读取并建立保留
    li   x13, 100
    bne  x12, x13, fail      # 检查读出的旧值是否为 100

    li   x14, 200
    sc.w x15, x14, 0(x10)    # 尝试写入 200
    bnez x15, fail           # SC 必须成功 (返回 0)

    lw   x16, 0(x10)
    li   x17, 200
    bne  x16, x17, fail      # 确认内存已更新为 200


    # ==========================================
    # 测试 2: 值比较失败 (CAS Fail)
    # ==========================================
    lr.w x12, 0(x10)         # 读取当前值 (应为 200)
    li   x13, 999            # 期望值是 999 (故意设错)
    bne  x12, x13, test3     # 发现不匹配，跳过 SC，直接进入测试 3


    # ==========================================
    # 测试 3: 保留集被破坏 (SC 预期失败)
    # ==========================================
test3:                       # 【标签】
    li   x18, 0x0000000080002008     # 另一个合法的 4 字节对齐地址 (64位完整地址)
    li   x19, 55
    sw   x19, 0(x18)         # 初始化第二个地址

    lr.w x12, 0(x10)         # 对地址 A 建立保留
    lr.w x20, 0(x18)         # 【关键】对地址 B 建立保留，这会覆盖地址 A 的保留集！

    li   x14, 300
    sc.w x15, x14, 0(x10)    # 尝试写回地址 A
    beqz x15, fail           # 【断言】因为保留集已被覆盖，SC 必须失败 (返回值非 0)

    lw   x21, 0(x10)
    li   x22, 200            # 内存应该保持之前的值 200 不变
    bne  x21, x22, fail      # 如果内存被意外修改，则测试失败


    # ==========================================
    # 测试 4: 正常结束占位 (可根据需要扩展异常测试)
    # ==========================================
test4:                       # 【标签】
    nop


pass:
    li  t0, 0x0000000090000000             # 输出端口地址高 12 位
    li   t1, 'P'             # 打印 'P' 表示 Pass
    sb   t1, 0(t0)
    li   t1, '\n'            # 换行
    sb   t1, 0(t0)
    j    end

fail:
    li  t0, 0x0000000090000000             # 输出端口地址高 12 位
    li   t1, 'F'             # 打印 'F' 表示 Fail
    sb   t1, 0(t0)
    li   t1, '\n'            # 换行
    sb   t1, 0(t0)
    j    end

end:
    ebreak                   # 触发断点，结束仿真或执行

