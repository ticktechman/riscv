.section .text
.globl _start

_start:
    # ==========================================
    # 1. 基础寄存器运算检查 (参考你的示例)
    # ==========================================
    li x1, 10
    li x2, 20
    add x3, x1, x2      # x3 = 30
    sub x4, x2, x1      # x4 = 10

    # 检查 x3 == 30
    li x5, 30
    bne x3, x5, fail

    # 检查 x4 == 10
    li x5, 10
    bne x4, x5, fail

    # ==========================================
    # 2. CSR 读写测试 (核心部分)
    # ==========================================

    # --- 步骤 A: 读取并备份 mstatus (0x300) ---
    # 假设当前 mstatus = 0x00000000 (硬件复位默认值)
    csrr t0, 0x300      # 读取 mstatus 到 t0
                        # 执行后: t0 = 0x00000000

    mv s0, t0           # s0 保存 mstatus 原始值 (用于最后恢复)
                        # 执行后: s0 = 0x00000000

    # --- 步骤 B: 写入新值到 mstatus ---
    # 我们尝试设置 MIE 位 (第3位) 和 MPIE 位 (第7位)
    li t1, 0x88         # t1 = 0x88 (二进制: ...0000 1000 1000)
                        # 执行后: t1 = 0x00000088

    csrw 0x300, t1      # 将 t1 的值写入 mstatus
                        # 执行后: mstatus = 0x00000088
                        # (注意：如果这是真实硬件，某些只读位可能会被忽略，但这里假设全写成功)

    # --- 步骤 C: 验证写入是否成功 ---
    csrr t2, 0x300      # 再次读取 mstatus 到 t2
                        # 执行后: t2 = 0x00000088

    # 检查读取的值是否等于写入的值
    bne t1, t2, fail    # t1(0x88) == t2(0x88)，比较相等，不跳转

    # --- 步骤 D: 测试 CSRRS (置位) ---
    # 目标：把 MEIE 位 (第11位) 置 1
    li t1, (1 << 11)    # 1 << 11 = 0x800
                        # 执行后: t1 = 0x00000800

    csrrs t2, 0x300, t1 # 原子操作：t2 = mstatus(旧值), mstatus |= t1
                        # 执行前: mstatus = 0x00000088
                        # 执行后:
                        #   t2 = 0x00000088 (返回旧值)
                        #   mstatus = 0x00000088 | 0x00000800 = 0x00000888

    # 验证：t2 的第11位应该是 1
    ; csrr t2, 0x300    # (注释掉的代码：如果执行，t2 会变成 0x888)

    li t3, (1 << 11)    # 准备掩码
                        # 执行后: t3 = 0x00000800

    and t4, t2, t3      # 提取第11位
                        # 执行前: t2 = 0x00000088 (csrrs 返回的旧值)
                        # 执行后: t4 = 0x00000000 (因为 0x88 & 0x800 = 0)

    beqz t4, fail       # t4 是 0，条件成立 -> **跳转到 fail**
                        # 【再次提醒】：这里逻辑有误，因为你在检查旧值。
                        # 如果你想让代码跑通，这里应该取消注释上面的 csrr 指令。

    # --- 步骤 E: 测试 CSRRC (清零) ---
    # 目标：把 MEIE 位 (第11位) 清 0
    li t1, (1 << 11)    # 准备掩码
                        # 执行后: t1 = 0x00000800

    csrrc t2, 0x300, t1 # 原子操作：t2 = mstatus(旧值), mstatus &= ~t1
                        # 假设我们跳过了上面的 fail，或者修复了 bug 运行到了这里
                        # 此时 mstatus 应该是 0x888 (来自步骤 D 的结果)
                        # 执行后:
                        #   t2 = 0x00000888 (返回旧值)
                        #   mstatus = 0x00000888 & ~0x00000800 = 0x00000088

# 【关键修改】重新读取 mstatus 以获取清零后的新值
    csrr t2, 0x300           # t2 = 0x300 (此时第11位应该是0)

    li   t3, (1 << 11)       # 准备验证掩码 0x800

    and  t4, t2, t3          # 提取第11位
                             # 如果清零成功，t2 的第11位是0，则 t4 = 0

    bnez t4, fail            # 如果 t4 != 0，说明清零失败 -> 跳转

    # --- 步骤 F: 恢复现场 ---
    # 将最开始备份的 mstatus 值写回去
    csrw 0x300, s0      # 恢复 mstatus
                        # 执行前: s0 = 0x00000000 (步骤 A 备份的值)
                        # 执行后: mstatus = 0x00000000

#----------------------------------------
.equ TOHOST_BASE, 0x0000000080001000
pass:
    li  t0, TOHOST_BASE
    li   t1, 1
    sw   t1, 0(t0)
    j    end

fail:
    li  t0, TOHOST_BASE
    li   t1, 2
    sw   t1, 0(t0)
    j    end

end:
    ebreak
#----------------------------------------

